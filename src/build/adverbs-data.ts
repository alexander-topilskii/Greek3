export const ALL_ADVERB_PARADIGMS: AdverbParadigm[] = [
  PLACE_ADVERB_PARADIGM,
  TIME_ADVERB_PARADIGM,
  MANNER_ADVERB_PARADIGM,
  DEGREE_ADVERB_PARADIGM,
  CORRELATIVE_ADVERB_PARADIGM,
];

/**
 * Map an adverb word slug or title to its paradigm, initial face position, variant, and highlight term.
 */
export function getParadigmForAdverbWordSlug(slug: string): {
  paradigm: AdverbParadigm;
  initialPosition: AdverbFacePosition;
  initialVariant: string;
  highlightForm?: string;
} | null {
  const norm = slug.replace(/^words\//, '').replace(/\.md$/, '').replace(/\.html$/, '');

  // 1. PLACE
  if (
    norm.includes('εδώ') ||
    norm.includes('εκεί') ||
    norm.includes('μέσα') ||
    norm.includes('έξω') ||
    norm.includes('πάνω') ||
    norm.includes('κάτω') ||
    norm.includes('μπροστά') ||
    norm.includes('πίσω') ||
    norm.includes('αριστερά') ||
    norm.includes('δεξιά') ||
    norm.includes('ευθεία') ||
    norm.includes('κοντά') ||
    norm.includes('μακριά') ||
    norm.includes('δίπλα') ||
    norm.includes('ανάμεσα') ||
    norm.includes('παντού') ||
    norm.includes('πουθενά') ||
    norm.includes('κάπου') ||
    norm.includes('παρακάτω') ||
    norm.includes('μαζί')
  ) {
    let position: AdverbFacePosition = 'left';
    let highlight = '';

    if (norm.includes('εδώ κοντά') || norm.includes('κοντά')) {
      position = 'left';
      highlight = 'κοντά';
    } else if (norm.includes('μακριά')) {
      position = 'left';
      highlight = 'μακριά';
    } else if (norm.includes('εδώ')) {
      position = norm.includes('сюда') ? 'center' : 'left';
      highlight = 'εδώ';
    } else if (norm.includes('εκεί')) {
      position = norm.includes('туда') ? 'center' : 'left';
      highlight = 'εκεί';
    } else if (norm.includes('μέσα') || norm.includes('έξω') || norm.includes('πάνω') || norm.includes('κάτω')) {
      position = 'left';
      highlight = norm.includes('μέσα') ? 'μέσα' : norm.includes('έξω') ? 'έξω' : norm.includes('πάνω') ? 'πάνω' : 'κάτω';
    } else if (
      norm.includes('μπροστά') ||
      norm.includes('πίσω') ||
      norm.includes('αριστερά') ||
      norm.includes('δεξιά') ||
      norm.includes('ευθεία') ||
      norm.includes('παρακάτω')
    ) {
      position = 'center';
      highlight = norm.includes('μπροστά')
        ? 'μπροστά'
        : norm.includes('πίσω')
        ? 'πίσω'
        : norm.includes('αριστερά')
        ? 'αριστερά'
        : norm.includes('δεξιά')
        ? 'δεξιά'
        : norm.includes('ευθεία')
        ? 'ευθεία'
        : 'παρακάτω';
    } else if (norm.includes('από') || norm.includes('παντού') || norm.includes('πουθενά') || norm.includes('δίπλα') || norm.includes('ανάμεσα')) {
      position = 'right';
      highlight = norm.includes('παντού')
        ? 'παντού'
        : norm.includes('πουθενά')
        ? 'πουθενά'
        : norm.includes('δίπλα')
        ? 'δίπλα'
        : norm.includes('ανάμεσα')
        ? 'ανάμεσα'
        : 'από';
    }

    return {
      paradigm: PLACE_ADVERB_PARADIGM,
      initialPosition: position,
      initialVariant: 'coords',
      highlightForm: highlight || undefined,
    };
  }

  // 2. TIME
  if (
    norm.includes('τώρα') ||
    norm.includes('σήμερα') ||
    norm.includes('αύριο') ||
    norm.includes('χθες') ||
    norm.includes('προχτές') ||
    norm.includes('μεθαύριο') ||
    norm.includes('απόψε') ||
    norm.includes('φέτος') ||
    norm.includes('πέρυσι') ||
    norm.includes('πρόπερσι') ||
    norm.includes('νωρίς') ||
    norm.includes('αργά') ||
    norm.includes('αργότερα') ||
    norm.includes('πριν') ||
    norm.includes('μετά') ||
    norm.includes('σύντομα') ||
    norm.includes('ήδη') ||
    norm.includes('ακόμα') ||
    norm.includes('πάντα') ||
    norm.includes('συχνά') ||
    norm.includes('συνήθως') ||
    norm.includes('σπάνια') ||
    norm.includes('ποτέ') ||
    norm.includes('κάποτε') ||
    norm.includes('γενικά')
  ) {
    let position: AdverbFacePosition = 'center';
    let variant = 'timeline';
    let highlight = '';

    if (norm.includes('χθες') || norm.includes('προχτές') || norm.includes('πριν') || norm.includes('πέρυσι') || norm.includes('πρόπερσι')) {
      position = 'left';
      highlight = norm.includes('χθες') ? 'χθες' : norm.includes('προχτές') ? 'προχτές' : norm.includes('πριν') ? 'πριν' : 'πέρυσι';
    } else if (norm.includes('αύριο') || norm.includes('μεθαύριο') || norm.includes('μετά') || norm.includes('αργότερα') || norm.includes('σύντομα')) {
      position = 'right';
      highlight = norm.includes('αύριο') ? 'αύριο' : norm.includes('μεθαύριο') ? 'μεθαύριο' : norm.includes('μετά') ? 'μετά' : 'σύντομα';
    } else if (norm.includes('πάντα') || norm.includes('συχνά') || norm.includes('συνήθως') || norm.includes('σπάνια') || norm.includes('ποτέ')) {
      variant = 'frequency';
      position = norm.includes('πάντα') ? 'left' : norm.includes('σπάνια') || norm.includes('ποτέ') ? 'right' : 'center';
      highlight = norm.includes('πάντα') ? 'πάντα' : norm.includes('συχνά') ? 'συχνά' : norm.includes('ποτέ') ? 'ποτέ' : 'σπάνια';
    } else {
      position = 'center';
      highlight = norm.includes('τώρα') ? 'τώρα' : norm.includes('σήμερα') ? 'σήμερα' : norm.includes('απόψε') ? 'απόψε' : 'ήδη';
    }

    return {
      paradigm: TIME_ADVERB_PARADIGM,
      initialPosition: position,
      initialVariant: variant,
      highlightForm: highlight || undefined,
    };
  }

  // 3. DEGREE
  if (
    norm.includes('πάρα πολύ') ||
    norm.includes('πολύ') ||
    norm.includes('περισσότερο') ||
    norm.includes('λιγότερο') ||
    norm.includes('λίγο') ||
    norm.includes('αρκετά') ||
    norm.includes('καθόλου') ||
    norm.includes('σχεδόν') ||
    norm.includes('περίπου')
  ) {
    let position: AdverbFacePosition = 'center';
    let highlight = '';

    if (norm.includes('καθόλου') || norm.includes('λίγο') || norm.includes('λιγότερο') || norm.includes('σχεδόν') || norm.includes('περίπου')) {
      position = 'left';
      highlight = norm.includes('καθόλου') ? 'καθόλου' : norm.includes('λίγο') ? 'λίγο' : norm.includes('λιγότερο') ? 'λιγότερο' : 'περίπου';
    } else if (norm.includes('πάρα πολύ') || norm.includes('πολύ')) {
      position = 'right';
      highlight = norm.includes('πάρα πολύ') ? 'πάρα πολύ' : 'πολύ';
    } else {
      position = 'center';
      highlight = norm.includes('αρкеτά') ? 'αρкеτά' : 'περισσότερο';
    }

    return {
      paradigm: DEGREE_ADVERB_PARADIGM,
      initialPosition: position,
      initialVariant: 'scale',
      highlightForm: highlight || undefined,
    };
  }

  // 4. QUESTIONS AND CORRELATIVES
  if (
    norm.includes('πού') ||
    norm.includes('πότε') ||
    norm.includes('πώς') ||
    norm.includes('γιατί') ||
    norm.includes('πόσο') ||
    norm.includes('έτσι') ||
    norm.includes('κάπως')
  ) {
    let position: AdverbFacePosition = 'left';
    let highlight = '';

    if (norm.includes('πού') || norm.includes('πότε') || norm.includes('πώς') || norm.includes('γιατί') || norm.includes('πόσο')) {
      position = 'left';
      highlight = norm.includes('πού') ? 'πού' : norm.includes('πότε') ? 'πότε' : norm.includes('πώς') ? 'πώς' : 'γιατί';
    } else if (norm.includes('έτσι')) {
      position = 'center';
      highlight = 'έτσι';
    } else {
      position = 'right';
      highlight = 'κάπως';
    }

    return {
      paradigm: CORRELATIVE_ADVERB_PARADIGM,
      initialPosition: position,
      initialVariant: 'matrix',
      highlightForm: highlight || undefined,
    };
  }

  // 5. MANNER (default for qualitative adverbs, modal adverbs, and languages)
  if (
    norm.includes('καλά') ||
    norm.includes('άσχημα') ||
    norm.includes('γρήγορα') ||
    norm.includes('εύκοла') ||
    norm.includes('κανονικά') ||
    norm.includes('ευγενικά') ||
    norm.includes('απαλά') ||
    norm.includes('αναλυτικά') ||
    norm.includes('συγκεκριμένα') ||
    norm.includes('παράλληλα') ||
    norm.includes('καλύτερα') ||
    norm.includes('άριστα') ||
    norm.includes('σίγουρα') ||
    norm.includes('δυστυχώς') ||
    norm.includes('σοβαρά') ||
    norm.includes('φανταστικά') ||
    norm.includes('επιτέλους') ||
    norm.includes('δωρεάν') ||
    norm.includes('ακριβώς') ||
    norm.endsWith('ικά')
  ) {
    let position: AdverbFacePosition = 'left';
    let variant = 'degrees';
    let highlight = '';

    if (norm.includes('καλύτερα') || norm.includes('χειρότερα') || norm.includes('γρηγορότερα') || norm.includes('ευκολότερα')) {
      position = 'center';
      highlight = norm.includes('καλύτερα') ? 'καλύτερα' : 'γρηγορότερα';
    } else if (norm.includes('άριστα') || norm.includes('φανταστικά') || norm.includes('τέλεια') || norm.includes('συγκεκριμένα')) {
      position = 'right';
      highlight = norm.includes('άριστα') ? 'άριστα' : norm.includes('φανταστικά') ? 'φανταστικά' : 'συγκεκριμένα';
    } else if (norm.includes('ακριβώς') || norm.includes('δυστυχώς') || norm.endsWith('ικά')) {
      variant = 'endings';
      position = norm.endsWith('ικά') ? 'right' : 'center';
      highlight = norm.includes('ακριβώς') ? 'ακριβώς' : norm.includes('δυστυχώς') ? 'δυστυχώς' : 'ελληνικά';
    } else {
      position = 'left';
      highlight = norm.includes('καλά')
        ? 'καλά'
        : norm.includes('άσχημα')
        ? 'άσχημα'
        : norm.includes('γρήγορα')
        ? 'γρήγορα'
        : norm.includes('εύκολα')
        ? 'εύκολα'
        : 'κανονικά';
    }

    return {
      paradigm: MANNER_ADVERB_PARADIGM,
      initialPosition: position,
      initialVariant: variant,
      highlightForm: highlight || undefined,
    };
  }

  // Fallback: if category is adverbs, default to manner or place
  if (norm.startsWith('adverbs/')) {
    return {
      paradigm: MANNER_ADVERB_PARADIGM,
      initialPosition: 'left',
      initialVariant: 'degrees',
    };
  }

  return null;
}
