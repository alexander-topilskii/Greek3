export type AdverbFacePosition = 'left' | 'center' | 'right';

export interface AdverbCell {
  label: string;
  greek: string;
  ru: string;
  hint?: string;
  slug?: string;
}

export interface AdverbRow {
  left: AdverbCell;
  right: AdverbCell;
}

export interface AdverbFace {
  id: string;
  position: AdverbFacePosition;
  title: string;
  subtitle: string;
  colLeftTitle: string;
  colRightTitle: string;
  rows: AdverbRow[];
}

export interface AdverbVariant {
  id: string;
  label: string;
  faces: Record<AdverbFacePosition, AdverbFace>;
  extraNotes?: {
    title: string;
    description?: string;
    examples: { greek: string; ru: string }[];
  };
}

export interface AdverbParadigm {
  id: string;
  title: string;
  tabLabel: string;
  defaultPosition?: AdverbFacePosition;
  defaultVariant?: string;
  variants: AdverbVariant[];
}

