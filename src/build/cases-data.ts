export type CaseType = 'nominative' | 'accusative' | 'genitive';

export interface CaseCell {
  label: string;
  from?: string;
  to?: string;
  greek: string;
  ru: string;
  rule?: string;
  hint?: string;
  slug?: string;
}

export interface CaseRow {
  left: CaseCell;
  right: CaseCell;
}

export interface CaseFace {
  case: CaseType;
  title: string;
  subtitle: string;
  colLeftTitle: string;
  colRightTitle: string;
  rows: CaseRow[];
}

export interface CaseVariant {
  id: string;
  label: string;
  faces: Record<CaseType, CaseFace>;
  extraNotes?: {
    title: string;
    description?: string;
    examples: { greek: string; ru: string }[];
  };
}

export interface CaseParadigm {
  id: string;
  title: string;
  tabLabel: string;
  defaultCase?: CaseType;
  defaultVariant?: string;
  variants: CaseVariant[];
}

