export function getParadigmForCaseSubDir(subDir: string): CaseParadigm | null {
  const normalized = subDir.toLowerCase().replace(/^\/?words\/cases\/?/, '').replace(/\/.*$/, '');
  const theme = ALL_CASE_THEMES.find((t) => t.subDir === normalized || t.id === normalized);
  return theme?.paradigm ?? null;
}

export function getCaseThemeInfo(slug: string): CaseThemeInfo | null {
  const norm = slug.toLowerCase();
  if (norm.includes('управление') || norm.includes('government') || norm.includes('διακυβέρνηση')) {
    return ALL_CASE_THEMES.find((t) => t.id === 'government') ?? null;
  }
  if (norm.includes('adjective') || norm.includes('прилагательн')) {
    return ALL_CASE_THEMES.find((t) => t.id === 'adjectives') ?? null;
  }
  if (norm.includes('article') || norm.includes('артикл') || norm.includes('предлог')) {
    return ALL_CASE_THEMES.find((t) => t.id === 'articles') ?? null;
  }
  return ALL_CASE_THEMES.find((t) => t.id === 'nouns') ?? null;
}

export function getParadigmForCaseWordSlug(slug: string): {
  paradigm: CaseParadigm;
  initialCase: CaseType;
  initialVariant: string;
  highlightForm?: string;
} | null {
  const norm = slug.replace(/^words\//, '').replace(/\.md$/, '').replace(/\.html$/, '');

  if (norm.includes('именительный') || norm.includes('ονομαστική')) {
    return {
      paradigm: NOUNS_CASE_PARADIGM,
      initialCase: 'nominative',
      initialVariant: 'endings',
      highlightForm: 'ονομαστική',
    };
  }

  if (norm.includes('винительный') || norm.includes('αιτιατική')) {
    return {
      paradigm: NOUNS_CASE_PARADIGM,
      initialCase: 'accusative',
      initialVariant: 'endings',
      highlightForm: 'αιτιατική',
    };
  }

  if (norm.includes('родительный') || norm.includes('γενική')) {
    return {
      paradigm: NOUNS_CASE_PARADIGM,
      initialCase: 'genitive',
      initialVariant: 'endings',
      highlightForm: 'γενική',
    };
  }

  if (norm.includes('управление') || norm.includes('verb government') || norm.includes('διακυβέρνηση')) {
    return {
      paradigm: VERB_GOVERNMENT_PARADIGM,
      initialCase: 'accusative',
      initialVariant: 'direct',
      highlightForm: 'διακυβέρνηση',
    };
  }

  return null;
}
