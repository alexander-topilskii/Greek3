export const ALL_CASE_PARADIGMS: CaseParadigm[] = [
  NOUNS_CASE_PARADIGM,
  ADJECTIVES_CASE_PARADIGM,
  ARTICLES_PREPOSITIONS_PARADIGM,
  VERB_GOVERNMENT_PARADIGM,
];

export function getParadigmForCaseWordSlug(slug: string): {
  paradigm: CaseParadigm;
  initialCase: CaseType;
  initialVariant: string;
  highlightForm?: string;
} | null {
  const norm = slug.replace(/^words\//, '').replace(/\.md$/, '').replace(/\.html$/, '');

  if (norm.includes('именительный') || norm.includes('ονομαστική')) {
    return {
      paradigm: NOUNS_CASE_PARADIGM,
      initialCase: 'nominative',
      initialVariant: 'endings',
      highlightForm: 'ονομαστική',
    };
  }

  if (norm.includes('винительный') || norm.includes('αιτιατική')) {
    return {
      paradigm: NOUNS_CASE_PARADIGM,
      initialCase: 'accusative',
      initialVariant: 'endings',
      highlightForm: 'αιτιατική',
    };
  }

  if (norm.includes('родительный') || norm.includes('γενική')) {
    return {
      paradigm: NOUNS_CASE_PARADIGM,
      initialCase: 'genitive',
      initialVariant: 'endings',
      highlightForm: 'γενική',
    };
  }

  if (norm.includes('управление') || norm.includes('verb government') || norm.includes('διακυβέρνηση')) {
    return {
      paradigm: VERB_GOVERNMENT_PARADIGM,
      initialCase: 'accusative',
      initialVariant: 'direct',
      highlightForm: 'διακυβέρνηση',
    };
  }

  return null;
}
