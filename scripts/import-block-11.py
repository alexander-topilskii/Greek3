def noun(key, fn, ru, greek, forms, group, topics=None):
    add(key, "nouns", fn, word_md(ru, greek, forms, topics=topics or ["Жильё"], wtype="noun", tip="ουσιαστικό"), group)


def verb(key, fn, ru, base, forms, group, tip="Τύπος Α"):
    add(key, "verbs", fn, word_md(ru, base, forms, topics=["Базовые глаголы"], wtype="verb", tip=tip), group)


def adj(key, fn, ru, greek, forms, group):
    add(key, "adjectives", fn, word_md(ru, greek, forms, wtype="adjective", tip="επίθετο"), group)


def pronoun(key, fn, ru, greek, forms, group):
    add(key, "pronouns", fn, word_md(ru, greek, forms, wtype="pronoun"), group)


def phrase(key, fn, ru, greek, forms, group, topics=None):
    add(key, "phrases", fn, word_md(ru, greek, forms, topics=topics or ["Жильё"], wtype="phrase"), group)


