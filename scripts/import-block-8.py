def find_exact(*needles: str) -> str | None:
    needles_l = [n.lower() for n in needles if n and len(n) >= 3]
    variants = {"τυρόπιτα": "τυρόπιτες", "τσιγάρα": "τσιγάρο"}
    for item in EXISTING:
        gl = item["gr_low"]
        tokens = re.split(r"[\s/·,;]+", gl)
        for n in needles_l:
            if n == gl or n in tokens:
                return item["rel"]
            alt = variants.get(n)
            if alt and (alt == gl or alt in tokens):
                return item["rel"]
    return None


def word_md(translation, base_greek, forms, *, level="A1", topics=None, wtype="", tip=""):
    fm = ["---", f"level: {level}"]
    if topics:
        fm.append(f"topics: [{', '.join(topics)}]")
    if wtype:
        fm.append(f"type: {wtype}")
    fm.append("---")
    lines = fm + ["", "# База", f"{translation} : {base_greek}", ""]
    if tip:
        lines += ["# Тип", tip, ""]
    lines.append("# Формы")
    for g, r in forms:
        lines.append(f"{g} - {r}")
    lines.append("")
    return "\n".join(lines)


NEW: dict[str, tuple[str, str, str, str]] = {}
