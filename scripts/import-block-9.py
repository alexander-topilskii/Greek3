def add(key: str, cat: str, filename: str, content: str, group: str) -> None:
    NEW[key] = (cat, filename, content, group)


def noun(key, filename, ru, greek, forms, group, topics=None, tip="ουσιαστικό"):
    add(key, "nouns", filename, word_md(ru, greek, forms, topics=topics or [], wtype="noun", tip=tip), group)


def verb(key, filename, ru, base, forms, group, tip="Τύπος Α", topics=None):
    add(
        key,
        "verbs",
        filename,
        word_md(ru, base, forms, topics=topics or ["Базовые глаголы"], wtype="verb", tip=tip),
        group,
    )


def adj(key, filename, ru, greek, forms, group, tip="επίθετο"):
    add(key, "adjectives", filename, word_md(ru, greek, forms, wtype="adjective", tip=tip), group)


def pronoun(key, filename, ru, greek, forms, group):
    add(key, "pronouns", filename, word_md(ru, greek, forms, wtype="pronoun"), group)


def phrase(key, filename, ru, greek, forms, group, topics=None, context=None):
    add(
        key,
        "phrases",
        filename,
        word_md(
            ru,
            greek,
            forms,
            topics=topics or ["Покупки"],
            wtype="phrase",
            context=context,
        ),
        group,
    )


