def find_existing(*needles: str) -> str | None:
    """Match only exact greek lemma / token (len>=3). Avoid short false positives."""
    needles_l = [n.lower() for n in needles if n and len(n) >= 3]
    variants = {
        "καινούριος": "καινούργιος",
        "αδερφός": "αδελφός",
        "αδερφή": "αδελφή",
    }
    for item in EXISTING:
        gl = item["gr_low"]
        tokens = re.split(r"[\s/·,;]+", gl)
        for n in needles_l:
            if n == gl or n in tokens:
                return item["rel"]
            alt = variants.get(n)
            if alt and (alt == gl or alt in tokens):
                return item["rel"]
    return None


def word_md(
    translation: str,
    base_greek: str,
    forms: list[tuple[str, str]],
    *,
    level: str = "A1",
    topics: list[str] | None = None,
    wtype: str = "",
    tip: str = "",
    context: list[tuple[str, str]] | None = None,
) -> str:
    fm = ["---", f"level: {level}"]
    if topics:
        fm.append(f"topics: [{', '.join(topics)}]")
    if wtype:
        fm.append(f"type: {wtype}")
    fm.append("---")
    lines = fm + ["", "# База", f"{translation} : {base_greek}", ""]
    if tip:
        lines += ["# Тип", tip, ""]
    lines.append("# Формы")
    for g, r in forms:
        lines.append(f"{g} - {r}")
    lines.append("")
    if context:
        lines.append("# Контекст")
        for g, r in context:
            lines.append(f"- **{g}** — {r}")
        lines.append("")
    return "\n".join(lines)


