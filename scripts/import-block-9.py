def resolve_target(target: str) -> str | None:
    overrides = {
        "verbs/ношу φοράω.md": "verbs/ношу (одежду) φοράω.md",
        "particles/конечно βεβαίως.md": "particles/конечно βέβαια.md",
    }
    target = overrides.get(target, target)
    if target in RESOLVED:
        return RESOLVED[target]
    if target in NEW:
        cat, fn, _, _ = NEW[target]
        return f"{cat}/{fn}"
    if "/" in target:
        if (ROOT / target).exists():
            return target
        needles = re.findall(r"[\u0370-\u03ff\u1f00-\u1fff]+", Path(target).stem.split(" ", 1)[-1])
        for n in needles:
            if len(n) < 4:
                continue
            hit = find_existing(n)
            if hit:
                return hit
        return None
    return find_existing(target)


