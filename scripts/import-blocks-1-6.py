def find_existing(*needles: str) -> str | None:
    """Return relative path under words/ if greek needle matches filename."""
    needles_l = [n.lower() for n in needles]
    for item in EXISTING:
        gl = item["gr_low"]
        for n in needles_l:
            if n == gl or gl.startswith(n + " ") or gl.endswith(" " + n) or f" {n}" in f" {gl}":
                return item["rel"]
            # exact token match ignoring punctuation
            tokens = re.split(r"[\s/·,;]+", gl)
            if n in tokens:
                return item["rel"]
    return None


def word_md(
    translation: str,
    base_greek: str,
    forms: list[tuple[str, str]],
    *,
    level: str = "A1",
    topics: list[str] | None = None,
    wtype: str = "",
    context: list[tuple[str, str]] | None = None,
    tip: str = "",
) -> str:
    fm = ["---", f"level: {level}"]
    if topics:
        fm.append(f"topics: [{', '.join(topics)}]")
    if wtype:
        fm.append(f"type: {wtype}")
    fm.append("---")
    lines = fm + ["", "# База", f"{translation} : {base_greek}", ""]
    if tip:
        lines += ["# Тип", tip, ""]
    lines.append("# Формы")
    for g, r in forms:
        lines.append(f"{g} - {r}")
    lines.append("")
    if context:
        lines.append("# Контекст")
        for g, r in context:
            lines.append(f"- **{g}** — {r}")
        lines.append("")
    return "\n".join(lines)


