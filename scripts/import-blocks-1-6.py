def write_block(n: int) -> None:
    items = []
    seen = set()
    for label, target in BLOCK_LINKS[n]:
        expanded = expand((label, target))
        if not expanded:
            # try NEW after remaps
            if target in NEW:
                cat, fn, _, _ = NEW[target]
                expanded = (label, f"{cat}/{fn}")
            else:
                print(f"WARN block {n}: unresolved {target}")
                continue
        label, rel = expanded
        if rel in seen:
            continue
        seen.add(rel)
        items.append((label, rel))
    lines = [f"# Блок {n}", "", "## Слова", ""]
    for label, rel in items:
        lines.append(f"[{label}](../../{rel})")
    lines.append("")
    (ROOT / "blocks" / f"{n:02d}" / "readme.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"block {n}: {len(items)} links")


