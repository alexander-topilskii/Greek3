NEW: dict[str, tuple[str, str, str, str]] = {}


def add(
    key: str,
    cat: str,
    filename: str,
    content: str,
    group: str,
) -> None:
    NEW[key] = (cat, filename, content, group)


def noun(key, filename, ru, greek, forms, group, topics=None, tip=""):
    add(
        key,
        "nouns",
        filename,
        word_md(ru, greek, forms, topics=topics or [], wtype="noun", tip=tip or "ουσιαστικό"),
        group,
    )


